import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { createServer } from 'node:http';
import { chromium } from 'playwright';

const base = process.env.CLINIC_TEST_URL || 'http://127.0.0.1:18765';
assert.equal(new URL(base).hostname, '127.0.0.1');
const host = createServer((req, res) => res.end('<iframe src="'+base+'/embed?lang=en"></iframe>'));
await new Promise(resolve => host.listen(0, 'localhost', resolve));
const browser = await chromium.launch({channel:'chrome'});
const name = 'QA-'+randomUUID();
let reference, replacement;
try {
  const owner = await browser.newContext({viewport:{width:390,height:844},hasTouch:true});
  const site = await owner.newPage();
  await site.goto('http://localhost:'+host.address().port);
  const frame = site.frameLocator('iframe');
  await frame.locator('.times button').first().click();
  const opened = owner.waitForEvent('page');
  await frame.getByRole('link',{name:'Continue on the clinic website'}).click();
  const page = await opened;
  await page.getByLabel('Patient name').fill(name);
  await page.getByLabel('Hong Kong phone number').fill('91234567');
  await page.getByLabel('Email (optional)').fill('qa@example.invalid');
  const notice = page.getByRole('link',{name:'Personal data collection notice (opens in a new tab)'});
  assert.equal(await notice.getAttribute('href'), '/privacy?lang=en');
  const consent = page.getByRole('checkbox');
  assert.equal(await consent.isChecked(), false);
  await consent.check();
  let saved = page.waitForResponse(r => r.url() === base+'/appointments' && r.request().method()==='POST');
  await page.getByRole('button',{name:'Confirm booking',exact:true}).click();
  const response = await saved;
  assert.equal(response.status(), 201);
  reference = (await response.json()).reference;
  await page.getByRole('link',{name:'My appointments'}).click();
  await page.getByText(reference,{exact:true}).waitFor();
  const old = Number(await page.locator('[name=expected_slot]').inputValue());
  const stranger = await browser.newPage();
  await stranger.goto(base);
  assert.equal((await stranger.request.get(base+'/appointments/'+reference+'/move')).status(),404);
  const csrf = await stranger.locator('meta[name=csrf-token]').getAttribute('content');
  assert.equal((await stranger.request.post(base+'/appointments/'+reference+'/cancel',{headers:{'X-CSRF-TOKEN':csrf,Accept:'application/json'},data:{expected_slot:old}})).status(),404);
  assert(!(await (await stranger.request.get(base+'/appointments/manage')).text()).includes(reference));

  await page.getByRole('link',{name:'Reschedule'}).click();
  await page.locator('.times button').first().click();
  saved = page.waitForResponse(r => r.request().method()==='PATCH');
  await page.getByRole('button',{name:'Confirm new time'}).click();
  assert.equal((await saved).status(),200);
  await page.getByRole('link',{name:'My appointments'}).click();
  const dest = Number(await page.locator('[name=expected_slot]').inputValue());
  assert.notEqual(dest,old);
  await page.getByText('Cancel appointment',{exact:true}).click();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth));
  await page.getByRole('button',{name:'Confirm cancellation'}).click();
  await page.getByText('Appointment cancelled.',{exact:true}).waitFor();
  const available = await (await page.request.get(base+'/availability')).json();
  assert(available.slots.some(s=>s.id===dest));
  assert(available.slots.some(s=>s.id===old));
  const again = await stranger.request.post(base+'/appointments',{headers:{'X-CSRF-TOKEN':csrf,Accept:'application/json'},data:{slot_id:dest,name:name+'-new',phone:'91234567'}});
  assert.equal(again.status(),201);
  replacement = (await again.json()).reference;
  assert.equal((await stranger.request.get(base+'/appointments/'+reference+'/move')).status(),404);
  console.log('PASS cross-site iframe handoff, encrypted email submission, same-browser management, foreign-session denial, reference-preserving move, cancellation and released-slot rebooking');
} finally {
  await browser.close();
  await new Promise(resolve=>host.close(resolve));
  if (replacement) execFileSync('php',['tests/check-history.php',name+'-new',replacement]);
  if (reference) execFileSync('php',['tests/check-history.php',name,reference]);
}
